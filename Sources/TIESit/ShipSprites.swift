    private static let accents: [ShipShape: UInt32] = [
        .xwing: 0xCA786A,
        .interceptor: 0xA89BBF,
        .bomber: 0xC3A46C,
        .scout: 0x85B89F,
        .gunship: 0x8DA8A1,
        .shuttle: 0xC9A27B,
        .fighter: 0x8AABC0,
        .speeder: 0xCC8EA0,
        .corvette: 0xB9A16E,
        .dart: 0x75ADB0,
    ]

    static let exhaustPorts: [ShipShape: [CGPoint]] = Dictionary(uniqueKeysWithValues: ShipShape.allCases.map { shape in
        let ports = rows[shape]!.enumerated().flatMap { row, line in
            line.enumerated().compactMap { col, pixel in
                pixel == "e" ? CGPoint(x: col, y: row) : nil
            }
        }
        return (shape, ports)
    })

    static let images: [ShipShape: CGImage] = Dictionary(uniqueKeysWithValues: ShipShape.allCases.map { shape in
        let pixels = rows[shape]!
        let palette: [Character: UInt32] = [
            "x": 0x293C4A, "s": 0x506775, "m": 0x9DAEB2, "h": 0xE6E8DF,
            "b": 0x427D96, "c": 0xA6D9DE, "r": accents[shape]!, "e": 0x9DDACB,
        ]
        var rgba = [UInt8]()
        for row in pixels {
            for pixel in row {
                if let rgb = palette[pixel] {
                    rgba.append(contentsOf: [UInt8((rgb >> 16) & 255), UInt8((rgb >> 8) & 255), UInt8(rgb & 255), 255])
                } else { rgba.append(contentsOf: [0, 0, 0, 0]) }
            }
        }
        let provider = CGDataProvider(data: Data(rgba) as CFData)!
        let image = CGImage(width: 32, height: 24, bitsPerComponent: 8, bitsPerPixel: 32,
                            bytesPerRow: 32 * 4, space: CGColorSpaceCreateDeviceRGB(),
                            bitmapInfo: CGBitmapInfo(rawValue: CGImageAlphaInfo.last.rawValue),
                            provider: provider, decode: nil, shouldInterpolate: false, intent: .defaultIntent)!
        return (shape, image)
    })

    static func draw(_ shape: ShipShape, in context: inout GraphicsContext, center: CGPoint, cell: CGFloat) {
        let image = images[shape]!
        let size = CGSize(width: CGFloat(image.width) * cell, height: CGFloat(image.height) * cell)
        context.withCGContext { cg in
            cg.interpolationQuality = .none
            cg.translateBy(x: center.x - size.width / 2, y: center.y + size.height / 2)
            cg.scaleBy(x: 1, y: -1)
            cg.draw(image, in: CGRect(origin: .zero, size: size))
        }
    }
